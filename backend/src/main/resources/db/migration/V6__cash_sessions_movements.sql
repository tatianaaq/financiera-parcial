-- V6: Caja por sucursal, sin alterar historiales de pagos o préstamos.
CREATE TABLE cash_sessions (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 agency_id bigint NOT NULL REFERENCES agencies(id),
 opened_by_id bigint NOT NULL REFERENCES app_users(id),
 opened_at timestamptz NOT NULL DEFAULT now(),
 opening_amount numeric(15,2) NOT NULL CHECK (opening_amount >= 0),
 status varchar(12) NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN','CLOSED')),
 closed_by_id bigint REFERENCES app_users(id),
 closed_at timestamptz,
 expected_amount numeric(15,2),
 counted_amount numeric(15,2),
 difference_amount numeric(15,2),
 closing_note varchar(500),
 CONSTRAINT cash_closed_fields CHECK (status='OPEN' OR (closed_at IS NOT NULL AND counted_amount IS NOT NULL AND counted_amount >= 0))
);
-- Una sola sesión abierta por sucursal; evita aperturas simultáneas.
CREATE UNIQUE INDEX uq_cash_open_agency ON cash_sessions(agency_id) WHERE status='OPEN';
CREATE INDEX idx_cash_sessions_agency_date ON cash_sessions(agency_id, opened_at DESC);
CREATE TABLE cash_movements (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 session_id bigint NOT NULL REFERENCES cash_sessions(id),
 recorded_by_id bigint NOT NULL REFERENCES app_users(id),
 created_at timestamptz NOT NULL DEFAULT now(),
 movement_type varchar(20) NOT NULL CHECK (movement_type IN ('INCOME','EXPENSE','REPLENISHMENT','INCIDENT')),
 amount numeric(15,2) NOT NULL CHECK (amount >= 0),
 description varchar(500) NOT NULL,
 request_key varchar(64) NOT NULL UNIQUE,
 CONSTRAINT incident_zero CHECK (movement_type <> 'INCIDENT' OR amount = 0),
 CONSTRAINT cash_positive_move CHECK (movement_type = 'INCIDENT' OR amount > 0)
);
CREATE INDEX idx_cash_movements_session ON cash_movements(session_id, created_at);
