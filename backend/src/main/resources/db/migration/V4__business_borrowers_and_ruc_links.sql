CREATE TABLE companies (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ruc varchar(11) NOT NULL UNIQUE,
    legal_name varchar(255) NOT NULL,
    tax_status varchar(50)
);
CREATE TABLE document_links (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_type varchar(5) NOT NULL,
    document_number varchar(11) NOT NULL UNIQUE,
    client_id bigint NOT NULL REFERENCES clients(id),
    company_id bigint REFERENCES companies(id),
    representative_name varchar(180),
    representative_role varchar(120),
    documents_reviewed boolean NOT NULL,
    checked_at timestamp(6) with time zone NOT NULL,
    checked_by_id bigint NOT NULL REFERENCES app_users(id),
    CONSTRAINT ck_document_link_type CHECK (document_type IN ('RUC10','RUC20')),
    CONSTRAINT ck_document_link_company CHECK ((document_type='RUC10' AND company_id IS NULL) OR (document_type='RUC20' AND company_id IS NOT NULL))
);
CREATE INDEX idx_document_links_client_id ON document_links(client_id);
