CREATE TABLE agencies (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    enabled boolean NOT NULL DEFAULT true,
    name varchar(255) NOT NULL,
    CONSTRAINT uk_agencies_name UNIQUE (name)
);

CREATE TABLE app_users (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    enabled boolean NOT NULL DEFAULT true,
    agency_id bigint,
    password varchar(255) NOT NULL,
    role varchar(255) NOT NULL,
    username varchar(255) NOT NULL,
    CONSTRAINT uk_app_users_username UNIQUE (username),
    CONSTRAINT uk_user_agency_role UNIQUE (agency_id, role),
    CONSTRAINT fk_app_users_agency FOREIGN KEY (agency_id) REFERENCES agencies (id)
);

CREATE TABLE clients (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    active boolean NOT NULL DEFAULT true,
    address varchar(255),
    agency_id bigint,
    dni varchar(8) NOT NULL,
    names varchar(255) NOT NULL,
    phone varchar(255),
    registered_at date,
    surnames varchar(255) NOT NULL,
    CONSTRAINT uk_client_agency_dni UNIQUE (agency_id, dni),
    CONSTRAINT fk_clients_agency FOREIGN KEY (agency_id) REFERENCES agencies (id)
);

CREATE TABLE loans (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    annual_rate numeric(38,2),
    agency_id bigint NOT NULL,
    client_id bigint NOT NULL,
    created_by_id bigint NOT NULL,
    disbursed_at date,
    installments integer NOT NULL,
    insurance boolean NOT NULL DEFAULT false,
    outstanding_principal numeric(38,2),
    principal numeric(38,2),
    status varchar(255) NOT NULL,
    CONSTRAINT fk_loans_agency FOREIGN KEY (agency_id) REFERENCES agencies (id),
    CONSTRAINT fk_loans_client FOREIGN KEY (client_id) REFERENCES clients (id),
    CONSTRAINT fk_loans_created_by FOREIGN KEY (created_by_id) REFERENCES app_users (id)
);

CREATE TABLE installments (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    due_date date,
    insurance_due numeric(38,2),
    insurance_paid numeric(38,2),
    interest_due numeric(38,2),
    interest_paid numeric(38,2),
    number integer NOT NULL,
    principal_due numeric(38,2),
    principal_paid numeric(38,2),
    status varchar(255),
    loan_id bigint NOT NULL,
    CONSTRAINT fk_installments_loan FOREIGN KEY (loan_id) REFERENCES loans (id)
);

CREATE TABLE payments (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    amount numeric(38,2),
    method varchar(255),
    paid_at date,
    receipt_image_data text,
    reference varchar(255),
    loan_id bigint NOT NULL,
    registered_by_id bigint NOT NULL,
    CONSTRAINT uk_payment_method_reference UNIQUE (method, reference),
    CONSTRAINT fk_payments_loan FOREIGN KEY (loan_id) REFERENCES loans (id),
    CONSTRAINT fk_payments_registered_by FOREIGN KEY (registered_by_id) REFERENCES app_users (id)
);

CREATE TABLE payment_allocations (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    installment_id bigint NOT NULL,
    insurance_amount numeric(38,2),
    interest_amount numeric(38,2),
    payment_id bigint NOT NULL,
    principal_amount numeric(38,2),
    CONSTRAINT fk_payment_allocations_installment FOREIGN KEY (installment_id) REFERENCES installments (id),
    CONSTRAINT fk_payment_allocations_payment FOREIGN KEY (payment_id) REFERENCES payments (id)
);

CREATE INDEX idx_app_users_agency_id ON app_users (agency_id);
CREATE INDEX idx_clients_agency_id ON clients (agency_id);
CREATE INDEX idx_loans_agency_id ON loans (agency_id);
CREATE INDEX idx_loans_client_id ON loans (client_id);
CREATE INDEX idx_loans_created_by_id ON loans (created_by_id);
CREATE INDEX idx_installments_loan_id ON installments (loan_id);
CREATE INDEX idx_payments_loan_id ON payments (loan_id);
CREATE INDEX idx_payments_registered_by_id ON payments (registered_by_id);
CREATE INDEX idx_payment_allocations_installment_id ON payment_allocations (installment_id);
CREATE INDEX idx_payment_allocations_payment_id ON payment_allocations (payment_id);
